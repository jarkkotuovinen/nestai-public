#!/bin/bash

# Script to update shell with deployed CloudFront URLs
# Run after: cdk deploy --all

set -e

echo "━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━"
echo "  Update Shell with CloudFront URLs"
echo "━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━"
echo

# Get CloudFormation outputs
echo "→ Fetching CloudFormation outputs..."

MAP_URL=$(aws cloudformation describe-stacks --stack-name MapRemoteStack --query "Stacks[0].Outputs[?OutputKey=='RemoteEntryURL'].OutputValue" --output text)
PERF_URL=$(aws cloudformation describe-stacks --stack-name PerfRemoteStack --query "Stacks[0].Outputs[?OutputKey=='RemoteEntryURL'].OutputValue" --output text)
CONTROLS_URL=$(aws cloudformation describe-stacks --stack-name ControlsRemoteStack --query "Stacks[0].Outputs[?OutputKey=='RemoteEntryURL'].OutputValue" --output text)
WS_URL=$(aws cloudformation describe-stacks --stack-name WebSocketStack --query "Stacks[0].Outputs[?OutputKey=='WebSocketURL'].OutputValue" --output text)

echo "✓ URLs retrieved"
echo
echo "Map Remote:      $MAP_URL"
echo "Perf Remote:     $PERF_URL"
echo "Controls Remote: $CONTROLS_URL"
echo "WebSocket:       $WS_URL"
echo

# Create .env.production
echo "→ Creating apps/shell/.env.production..."

cat > ../apps/shell/.env.production <<EOF
# CloudFront URLs (auto-generated by update-shell-urls.sh)
VITE_MAP_REMOTE_URL=$MAP_URL
VITE_PERF_REMOTE_URL=$PERF_URL
VITE_CONTROLS_REMOTE_URL=$CONTROLS_URL
EOF

echo "✓ Environment file created"
echo

# Update App.tsx WebSocket URL
echo "→ Updating WebSocket URL in App.tsx..."

# Backup original
cp ../apps/shell/src/App.tsx ../apps/shell/src/App.tsx.backup

# Update WebSocket URL (line 47)
sed -i.bak "s|new WebSocket('ws://localhost:8080')|new WebSocket('$WS_URL')|g" ../apps/shell/src/App.tsx
rm ../apps/shell/src/App.tsx.bak

echo "✓ App.tsx updated"
echo

# Rebuild shell
echo "→ Rebuilding shell..."
cd ../apps/shell
pnpm build
echo "✓ Shell rebuilt"
echo

# Redeploy shell
echo "→ Redeploying shell to CloudFront..."
cd ../../infrastructure
cdk deploy ShellStack --require-approval never
echo "✓ Shell redeployed"
echo

# Get shell URL
SHELL_URL=$(aws cloudformation describe-stacks --stack-name ShellStack --query "Stacks[0].Outputs[?OutputKey=='URL'].OutputValue" --output text)

echo
echo "━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━"
echo "✓ Shell Updated Successfully!"
echo "━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━"
echo
echo "Visit your app:"
echo "$SHELL_URL"
echo
echo "Note: CloudFront may take 5-10 minutes to fully propagate."
echo
